/// The `(name, location)` pairs Atlas offers for a provider (`AWS`, `GCP`, or `AZURE`).
pub fn regions(provider: &str) -> &'static [(&'static str, &'static str)] {
    match provider {
        "AWS" => AWS,
        "GCP" => GCP,
        "AZURE" => AZURE,
        _ => &[],
    }
}

